COIN = "($ᵗ Bool : ProbComp Bool)"
NAMES = ["a", "b", "c", "n", "m", "x", "y"]


# Expressions: a Lean rendering and a Python evaluator over an environment.

@dataclass
class Expr:
    text: str
    ty: str  # "nat" or "bool"
    run: object  # env -> value


def nat_const(k: int) -> Expr:
    return Expr(str(k), "nat", lambda env, k=k: k)


def var(name: str, ty: str) -> Expr:
    return Expr(name, ty, lambda env, name=name: env[name])


def gen_nat(rng: random.Random, scope: dict[str, str], depth: int = 0) -> Expr:
    nats = [v for v, t in scope.items() if t == "nat"]
    bools = [v for v, t in scope.items() if t == "bool"]
    choice = rng.random()
    if not nats or choice < 0.2:
        return nat_const(rng.randint(0, 3))
    if choice < 0.45 or depth > 0:
        return var(rng.choice(nats), "nat")
    if choice < 0.7:
        x = var(rng.choice(nats), "nat")
        y = gen_nat(rng, scope, depth + 1)
        return Expr(f"{x.text} + {y.text}", "nat", lambda env: x.run(env) + y.run(env))
    if bools:
        b = var(rng.choice(bools), "bool")
        k1, k2 = rng.randint(0, 3), rng.randint(0, 3)
        return Expr(f"(if {b.text} then {k1} else {k2})", "nat",
                    lambda env: k1 if b.run(env) else k2)
    return var(rng.choice(nats), "nat")


def gen_bool(rng: random.Random, scope: dict[str, str]) -> Expr:
    nats = [v for v, t in scope.items() if t == "nat"]
    bools = [v for v, t in scope.items() if t == "bool"]
    choice = rng.random()
    if bools and choice < 0.4:
        return var(rng.choice(bools), "bool")
    if bools and choice < 0.55:
        b = var(rng.choice(bools), "bool")
        return Expr(f"!{b.text}", "bool", lambda env: not b.run(env))
    if len(bools) >= 2 and choice < 0.75:
        p, q = rng.sample(bools, 2)
        return Expr(f"({p} && {q})", "bool", lambda env: env[p] and env[q])
    if nats:
        n = rng.choice(nats)
        k = rng.randint(0, 3)
        return Expr(f"({n} == {k})", "bool", lambda env: env[n] == k)
    if bools:
        return var(rng.choice(bools), "bool")
    return Expr("true", "bool", lambda env: True)


# Runs: a list of (weight, environment) pairs; failure drops the run.

Run = list[tuple[Fraction, dict]]


def bind(run: Run, name: str, value) -> Run:
    return [(w, {**env, name: value(env)}) for w, env in run]


@dataclass
class Program:
    lines: list[str] = field(default_factory=list)
    scope: dict[str, str] = field(default_factory=dict)
    mutable: set[str] = field(default_factory=set)
    run: Run = field(default_factory=lambda: [(Fraction(1), {})])
    tail: bool = False
    # Whether the tail runs in `OptionT ProbComp`. Its first draw fixes its monad, so a
    # `let some x ← … | failure` comes before any other draw of the tail.
    option: bool = False
    tail_draws: int = 0

    def fresh(self, rng: random.Random) -> str:
        # Shadow immutable bindings freely; never shadow a mutable one.
        options = [n for n in NAMES if n not in self.mutable]
        return rng.choice(options)

    def define(self, name: str, ty: str) -> None:
        self.scope[name] = ty
        self.mutable.discard(name)


def step(rng: random.Random, p: Program) -> None:
    """Append one item to the program, in the leading part or the imperative tail."""
    kinds = ["coin", "coin", "draw", "let", "have", "pair", "condDraw", "hole"]
    if p.tail:
        kinds += ["assign", "assign", "if", "if", "match", "match", "for", "for"]
    kinds += ["mut", "mut"]
    if p.option or p.tail_draws == 0:
        kinds.append("letElse")
    if not p.mutable:
        kinds = [k for k in kinds if k not in ("assign", "if", "match", "for")]
    kind = rng.choice(kinds)
    if kind == "coin":
        x = p.fresh(rng)
        p.lines.append(f"let {x} ← {COIN}")
        p.run = [(w / 2, {**env, x: v}) for w, env in p.run for v in (True, False)]
        p.define(x, "bool")
        p.tail_draws += p.tail
    elif kind == "hole":
        p.lines.append(f"let _ ← {COIN}")
        p.tail_draws += p.tail
    elif kind == "draw":
        e = gen_nat(rng, p.scope)
        x = p.fresh(rng)
        typed = rng.random() < 0.3
        binder = f"{x} : ℕ" if typed else x
        p.lines.append(f"let {binder} ← (pure ({e.text}) : ProbComp ℕ)")
        p.run = bind(p.run, x, e.run)
        p.define(x, "nat")
        p.tail_draws += p.tail
    elif kind == "condDraw":
        b = gen_bool(rng, p.scope)
        k1, k2 = rng.randint(0, 3), rng.randint(0, 3)
        x = p.fresh(rng)
        p.lines.append(f"let {x} ← (if {b.text} then pure {k1} else pure {k2} : ProbComp ℕ)")
        p.run = bind(p.run, x, lambda env: k1 if b.run(env) else k2)
        p.define(x, "nat")
        p.tail_draws += p.tail
    elif kind == "pair":
        e1, e2 = gen_nat(rng, p.scope), gen_nat(rng, p.scope)
        x, y = rng.sample([n for n in NAMES if n not in p.mutable], 2)
        p.lines.append(f"let ({x}, {y}) ← (pure ({e1.text}, {e2.text}) : ProbComp (ℕ × ℕ))")
        p.run = [(w, {**env, x: e1.run(env), y: e2.run(env)}) for w, env in p.run]
        p.define(x, "nat")
        p.define(y, "nat")
        p.tail_draws += p.tail
    elif kind in ("let", "have"):
        if rng.random() < 0.5 and any(t == "bool" for t in p.scope.values()):
            e = gen_bool(rng, p.scope)
        else:
            e = gen_nat(rng, p.scope)
        x = p.fresh(rng)
        # An unwritten type is left to the default instances, as in ordinary `do`.
        ty = "" if rng.random() < 0.3 else " : ℕ" if e.ty == "nat" else " : Bool"
        p.lines.append(f"{kind} {x}{ty} := {e.text}")
        p.run = bind(p.run, x, e.run)
        p.define(x, e.ty)
    elif kind == "mut":
        e = gen_nat(rng, p.scope)
        x = rng.choice([n for n in NAMES if n not in p.mutable])
        ty = "" if rng.random() < 0.3 else " : ℕ"
        p.lines.append(f"let mut {x}{ty} := {e.text}")
        p.run = bind(p.run, x, e.run)
        p.define(x, "nat")
        p.mutable.add(x)
        p.tail = True
    elif kind == "letElse":
        b = gen_bool(rng, p.scope)
        e = gen_nat(rng, p.scope)
        x = p.fresh(rng)
        p.lines.append(
            f"let some {x} ← (pure (if {b.text} then some ({e.text}) else none) : "
            f"OptionT ProbComp (Option ℕ)) | failure")
        p.run = [(w, {**env, x: e.run(env)}) for w, env in p.run if b.run(env)]
        p.define(x, "nat")
        p.tail = True
        p.option = True
        p.tail_draws += 1
    elif kind == "assign":
        x = rng.choice(sorted(p.mutable))
        e = gen_nat(rng, p.scope)
        p.lines.append(f"{x} := {e.text}")
        p.run = bind(p.run, x, e.run)
    elif kind == "if":
        x = rng.choice(sorted(p.mutable))
        b = gen_bool(rng, p.scope)
        e1 = gen_nat(rng, p.scope)
        if rng.random() < 0.5:
            p.lines.append(f"if {b.text} then {x} := {e1.text}")
            p.run = bind(p.run, x, lambda env: e1.run(env) if b.run(env) else env[x])
        else:
            e2 = gen_nat(rng, p.scope)
            p.lines.append(f"if {b.text} then {x} := {e1.text} else {x} := {e2.text}")
            p.run = bind(p.run, x, lambda env: e1.run(env) if b.run(env) else e2.run(env))
    elif kind == "match":
        bools = [v for v, t in p.scope.items() if t == "bool"]
        if not bools:
            return
        b = rng.choice(bools)
        x = rng.choice(sorted(p.mutable))
        e1, e2 = gen_nat(rng, p.scope), gen_nat(rng, p.scope)
        p.lines += [f"match {b} with", f"| true => {x} := {e1.text}",
                    f"| false => {x} := {e2.text}"]
        p.run = bind(p.run, x, lambda env: e1.run(env) if env[b] else e2.run(env))
    elif kind == "for":
        x = rng.choice(sorted(p.mutable))
        ks = [rng.randint(0, 2) for _ in range(rng.randint(1, 3))]
        p.lines.append(f"for i in {ks} do {x} := {x} + i")
        p.run = bind(p.run, x, lambda env: env[x] + sum(ks))


def gen_event(rng: random.Random, p: Program) -> tuple[str, object]:
    """A random event over the visible bindings, with values taken from the runs."""
    def atom():
        name = rng.choice(sorted(p.scope))
        values = sorted({env[name] for _, env in p.run}) or [0]
        if p.scope[name] == "bool":
            v = rng.choice([True, False])
            text = f"{name} = {'true' if v else 'false'}"
            return text, lambda env: env[name] == v
        k = rng.choice(values + [rng.randint(0, 3)])
        if rng.random() < 0.6:
            return f"{name} = {k}", lambda env: env[name] == k
        return f"{name} ≥ {k}", lambda env: env[name] >= k
    t1, f1 = atom()
    r = rng.random()
    if r < 0.5:
        return t1, f1
    t2, f2 = atom()
    if r < 0.8:
        return f"{t1} ∧ {t2}", lambda env: f1(env) and f2(env)
    return f"{t1} ∨ {t2}", lambda env: f1(env) or f2(env)


def gen_value(rng: random.Random, p: Program) -> tuple[str, object]:
    nats = [v for v, t in p.scope.items() if t == "nat"]
    if not nats:
        return "(1 : ℝ≥0∞)", lambda env: 1
    if len(nats) >= 2 and rng.random() < 0.4:
        x, y = rng.sample(nats, 2)
        return f"({x} + {y} : ℝ≥0∞)", lambda env: env[x] + env[y]
    x = rng.choice(nats)
    return f"({x} : ℝ≥0∞)", lambda env: env[x]


def lean_value(v: Fraction) -> str:
    if v.denominator == 1:
        return f"({v.numerator} : ℝ≥0∞)"
    return f"({v.numerator} / {v.denominator} : ℝ≥0∞)"


def gen_case(rng: random.Random, index: int) -> str:
    p = Program()
    # Start with a coin so every case has a random draw.
    x = rng.choice(NAMES)
    p.lines.append(f"let {x} ← {COIN}")
    p.run = [(Fraction(1, 2), {x: v}) for v in (True, False)]
    p.define(x, "bool")
    for _ in range(rng.randint(2, 6)):
        step(rng, p)
    expectation = index % 4 == 3
    if expectation:
        text, f = gen_value(rng, p)
        value = sum((w * f(env) for w, env in p.run), Fraction(0))
        notation, ret = "𝔼", text
    else:
        text, f = gen_event(rng, p)
        value = sum((w for w, env in p.run if f(env)), Fraction(0))
        notation, ret = "Pr", f"({text} : Prop)"
    body = "\n".join("  " + line for line in p.lines)
    ref_body = "\n".join("    " + line for line in p.lines)
    # The reference is one `do` block, in the monad of its failing draws when it has any.
    monad = " : OptionT ProbComp _" if p.option else ""
    v = lean_value(value)
    name = f"case{index:03}"
    return (
        f"\n/-- Case {index}: the notation. -/\n"
        f"theorem {name} : {notation}{{\n{body}}}[{text}] = {v} := by\n  ennreal_value\n"
        f"\n/-- Case {index}: Lean's `do`. -/\n"
        f"theorem {name}_do : {notation}{{let r ← (do\n{ref_body}\n    return {ret}{monad})}}[r] = {v} "
        f":= by\n  ennreal_value\n")


def render() -> dict[str, str]:
    """The test files by name: cases are numbered across files, from one stream of the seed."""
    rng = random.Random(SEED)
    cases = [gen_case(rng, i) for i in range(CASES)]
    return {f"Cases{k // PER_FILE + 1}.lean": HEADER + "".join(cases[k:k + PER_FILE]) + FOOTER
            for k in range(0, CASES, PER_FILE)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if the committed test file differs from the generated one")
    args = parser.parse_args()
    files = render()
    present = {p.name for p in OUT.glob("*.lean")} if OUT.is_dir() else set()
    if args.check:
        stale = sorted((present ^ files.keys()) |
                       {n for n in files.keys() & present if (OUT / n).read_text() != files[n]})
        if stale:
            print(f"{OUT.relative_to(ROOT)}: {', '.join(stale)} stale; "
                  "run scripts/gen-notation-differential.py", file=sys.stderr)
            return 1
        return 0
    OUT.mkdir(exist_ok=True)
    for name in present - files.keys():
        (OUT / name).unlink()
    for name, text in files.items():
        (OUT / name).write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
