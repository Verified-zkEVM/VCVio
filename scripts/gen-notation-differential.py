#!/usr/bin/env python3
"""Generate the differential tests of the probability notation.

Each generated case is a random sequence of coin flips, draws, `let`s, `have`s, shadowing,
patterns, `let mut` with reassignment, `if`, `match`, `for` and `let some x ← … | failure`,
observed by a random event or value. The case states, with the same exact value:

* the notation, `Pr{items}[t]` (or `𝔼{items}[v]`), which the notation translates itself;
* the reference, `Pr{let r ← (do items; return (t : Prop))}[r]`, where Lean's own `do`
  elaborates the whole sequence and the notation only sees a single draw;

where the value is computed here by running the sequence on every outcome of its coins. A
translation that observes the wrong binding, reorders a tuple or drops a failure changes the
notation's value and fails the proof.

It writes `VCVioTest/EvalDist/NotationDifferential/Cases*.lean`, which `VCVioTest.lean` imports.

Usage: scripts/gen-notation-differential.py [--check]
"""

from __future__ import annotations

